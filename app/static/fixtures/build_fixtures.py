"""Regenerate eight labelled dashboard samples through the shared backend.

Run: uv run python -m app.static.fixtures.build_fixtures
The samples are view projections, not full trace exports or evaluation results.
They use real deterministic rules and fixture agents, with zero live model calls.
The separate live-H01 through live-H05 files are retained roles-v6 live-run
projections, not generated fixtures. Their source recording hashes are embedded.
"""

import asyncio
import json
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import cast

from pydantic import JsonValue

from app.agents import AgentProvider, UnavailableProvider
from app.approvals import current_snapshot, review_plan
from app.contracts import (
    PlanningHooks,
    ResourceState,
    ReviewRequest,
    ScenarioSnapshot,
    StartRunRequest,
)
from app.coordinator import Coordinator
from app.planning import build_catalog, check_plan, joint_baseline, load_snapshot, select_fallback
from app.store import Store
from examples.backend_fixture import DissentFixtureProvider, FixtureProvider

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent
NAMES = (
    "consensus",
    "third-turn",
    "fallback",
    "no-feasible",
    "insufficient-data",
    "applied",
    "stale",
    "rejected",
)


async def build(name: str, original: ScenarioSnapshot, db_path: Path) -> dict[str, JsonValue]:
    snapshot = original
    if name in ("no-feasible", "insufficient-data"):
        facts = []
        for fact in snapshot.facts:
            if fact.fact_id == "overlay.fuel":
                assert isinstance(fact.value, dict)
                fact = fact.model_copy(
                    update={
                        "value": {
                            **fact.value,
                            "projected_fuel_at_earliest_kg": 0 if name == "no-feasible" else None,
                        }
                    }
                )
            facts.append(fact)
        snapshot = snapshot.model_copy(update={"facts": tuple(facts)})
    store = Store(db_path)
    resource = ResourceState(resource_id=snapshot.resource_id, revision=snapshot.resource_revision)
    store.register_scenario(snapshot, resource)
    provider: AgentProvider = UnavailableProvider() if name == "fallback" else FixtureProvider()
    if name == "third-turn":
        provider = DissentFixtureProvider()
    run, _ = store.create_run(
        StartRunRequest(scenario_id=snapshot.scenario_id, scenario_revision=snapshot.revision),
        name,
        provider.info,
        "INTEGRATED",
        45,
    )
    coordinator = Coordinator(
        store,
        PlanningHooks(build_catalog, check_plan, select_fallback),
        provider,
    )
    run = await coordinator.run(run.run_id)
    if name in ("applied", "rejected"):
        assert run.candidate is not None and run.expires_at is not None
        request = ReviewRequest(
            decision="APPROVE" if name == "applied" else "REJECT",
            plan_hash=run.candidate.plan_hash,
            scenario_revision=snapshot.revision,
            resource_revision=snapshot.resource_revision,
            ruleset_version=snapshot.ruleset_version,
            policy_version=snapshot.policy_version,
            expires_at=run.expires_at,
            reason="Decision recorded only in the generated sample database",
        )
        run = store.review(run.run_id, request, "sample-approval", "sample-operator", review_plan)
    elif name == "stale":
        revised = snapshot.model_copy(update={"revision": 2, "resource_revision": 2})
        store.revise_scenario(current_snapshot(revised, resource))
        run = store.get_run(run.run_id)

    payload = cast(dict[str, JsonValue], run.model_dump(mode="json"))
    payload.update(
        mode="fixture",
        sample_projection=True,
        plan_hash=run.plan_hash,
        mode_note="Sample view generated by the real checker and SQLite review gate. "
        "Agent replies are deterministic fixtures; zero live model calls. "
        "Only the shortlist is included; this is not a full audit export or evaluation.",
    )
    if run.catalog:
        catalog = run.catalog
        ids = set(catalog.shortlist_ids)
        if run.candidate:
            ids.add(run.candidate.candidate_id)
        payload["catalog_total_count"] = len(catalog.candidates)
        payload["catalog_feasible_count"] = sum(
            all(check.status == "PASS" for check in entry.checks) for entry in catalog.candidates
        )
        payload["catalog"] = catalog.model_copy(
            update={
                "candidates": tuple(e for e in catalog.candidates if e.plan.candidate_id in ids),
            }
        ).model_dump(mode="json")
        blockers: dict[str, JsonValue] = {}
        for entry in catalog.candidates:
            for check in entry.checks:
                if check.status != "PASS":
                    blockers[check.rule_id] = cast(int, blockers.get(check.rule_id, 0)) + 1
        payload["blockers"] = blockers
        fallback = select_fallback(snapshot, catalog)
        baseline = next(
            (e for e in catalog.candidates if e.plan.candidate_id == fallback.candidate_id), None
        )
        payload["baseline_b0"] = baseline.model_dump(mode="json") if baseline else None
        b1 = joint_baseline(catalog)
        payload["baseline_b1"] = b1.model_dump(mode="json") if b1 else None
    payload["events"] = [
        {
            "sequence": event.sequence,
            "event_type": event.event_type,
            "actor": event.actor,
            "payload": {
                key: value
                for key, value in event.payload.items()
                if key
                in (
                    "state",
                    "reason_code",
                    "resource_revision",
                    "decision",
                    "reason",
                    "role",
                    "round",
                    "turn",
                    "candidate_id",
                    "plan_hash",
                    "outcome",
                    "request_id",
                    "status",
                )
            },
        }
        for event in store.events(run.run_id)
    ]
    await provider.close()
    return payload


async def main() -> None:
    snapshot = load_snapshot(ROOT / "scenarios/organizer/D01.json", ROOT / "data")
    with TemporaryDirectory() as temporary:
        for name in NAMES:
            payload = await build(name, snapshot, Path(temporary) / f"{name}.sqlite3")
            (OUT / f"{name}.json").write_text(json.dumps(payload, indent=2) + "\n")
            print(f"Wrote {name}: {payload['negotiation_outcome']} / {payload['approval_state']}")


if __name__ == "__main__":
    asyncio.run(main())
